import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import { PGlite } from '@electric-sql/pglite';

test('guest submissions, private feedback, moderation and analytics are isolated', async () => {
  const db = new PGlite();
  const owner = randomUUID(), stranger = randomUUID();
  try {
    await db.exec(`create role anon; create role authenticated; create schema auth;
      create table auth.users(id uuid primary key,email text,email_confirmed_at timestamptz);
      create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
      grant usage on schema public to anon,authenticated;`);
    await db.exec(await readFile(new URL('../backend/guestbook.sql', import.meta.url),'utf8'));
    await db.query('insert into auth.users values($1,$2,now()),($3,$4,now())',[owner,'owner@example.invalid',stranger,'visitor@example.invalid']);
    await db.query('insert into tingtao_private.admins values($1)',['owner@example.invalid']);
    await db.query("select set_config('request.headers',$1,false)",[JSON.stringify({origin:'https://yana04152.github.io','x-forwarded-for':'192.0.2.1'})]);
    await db.exec('set role anon');
    const request = randomUUID();
    const submit = (id,visibility='public',body='愿每次重温，都多懂她一点。')=>db.query('select public.tt_submit_message($1,$2,$3,$4,$5,$6,$7)',['测试读者',body,'memory',visibility,'',2500,id]);
    await submit(request);
    await submit(request);
    await submit(randomUUID(),'private','只给整理者的反馈');
    assert.deepEqual((await db.query('select public.tt_public_messages() as p')).rows[0].p,{total:0,items:[]},'pending and private records stay invisible');
    await assert.rejects(db.query('select * from tingtao_private.messages'),/permission denied/);
    await assert.rejects(db.query('select public.tt_admin_stats()'),/permission denied/);
    await assert.rejects(submit(randomUUID(),'public','x'),/检查昵称/);
    await assert.rejects(db.query("select public.tt_submit_message('a','正文','memory','public','spam',2500,$1)",[randomUUID()]),/稍停/);
    const event=randomUUID(),visit=randomUUID();
    await db.query('select public.tt_track_view($1,$2,$3,$4)',[visit,'home','微博',event]);
    await db.query('select public.tt_track_view($1,$2,$3,$4)',[visit,'home','微博',event]);
    await db.query('select public.tt_track_view($1,$2,$3,$4)',[visit,'videos','微博',randomUUID()]);
    await db.exec('reset role');
    assert.equal((await db.query('select count(*)::int n from tingtao_private.messages')).rows[0].n,2,'duplicate submissions create one message');
    const records=(await db.query('select id,visibility from tingtao_private.messages')).rows;
    const pub=records.find(r=>r.visibility==='public'),priv=records.find(r=>r.visibility==='private');
    await db.query("select set_config('request.jwt.claim.sub',$1,false)",[stranger]);
    await db.exec('set role authenticated');
    await assert.rejects(db.query('select public.tt_admin_stats()'),/仅网站整理者/);
    await assert.rejects(db.query('select public.tt_admin_update($1,$2,$3)',[pub.id,'approved','冒充回复']),/仅网站整理者/);
    await db.exec('reset role');
    await db.query("select set_config('request.jwt.claim.sub',$1,false)",[owner]);
    await db.exec('set role authenticated');
    const stats=(await db.query('select public.tt_admin_stats() s')).rows[0].s;
    assert.equal(stats.today_views,2);assert.equal(stats.today_visits,1);assert.equal(stats.pending,2);assert.equal(stats.daily.length,14);
    await db.query('select public.tt_admin_update($1,$2,$3)',[pub.id,'approved','谢谢你的文字。']);
    await assert.rejects(db.query('select public.tt_admin_update($1,$2,$3)',[priv.id,'approved',null]),/私密反馈不能/);
    await db.query('select public.tt_admin_update($1,$2,$3)',[priv.id,'handled','已核对']);
    await db.query('select public.tt_track_view($1,$2,$3,$4)',[randomUUID(),'home','直接访问',randomUUID()]);
    assert.equal((await db.query('select public.tt_admin_stats() s')).rows[0].s.today_views,2,'owner does not count as visitor');
    await db.exec('reset role');await db.query("select set_config('request.jwt.claim.sub','',false)");await db.exec('set role anon');
    const wall=(await db.query('select public.tt_public_messages() p')).rows[0].p;
    assert.equal(wall.total,1);assert.equal(wall.items[0].reply,'谢谢你的文字。');assert.equal(wall.items[0].visibility,undefined);assert.equal(wall.items[0].request_id,undefined);
    for(let i=0;i<6;i++)await submit(randomUUID());
    await assert.rejects(submit(randomUUID()),/操作有些频繁/);
    await db.exec('reset role');
    const settings=await db.query('select bucket from tingtao_private.rate_limits');
    assert(settings.rows.every(r=>!r.bucket.includes('192.0.2.1')),'raw IP is not persisted');
  } finally { await db.close(); }
});
